/**
 * عنوان الموقع — يُشارَك به رابط الملف، ومنه تُفتح لوحة التحكم.
 *
 * **لا يُكتب نطاقٌ في الكود**: النطاق لم يُحسم بعد، والمكتوب اليوم يبقى
 * في ملفٍّ منسيٍّ بعد أن يُحسم. فيُقرأ من البيئة باسمه في كل مضيف —
 * `SITE_URL` على الخادم، و`NEXT_PUBLIC_SITE_URL` في الويب، و
 * `EXPO_PUBLIC_SITE_URL` على الجوّال — وفراغُه ليس عطلاً: ما يحتاجه
 * يختفي (زرّ اللوحة، ورابط المشاركة) وما لا يحتاجه يعمل.
 */
export const SITE_URL: string =
  process.env.SITE_URL ??
  process.env.NEXT_PUBLIC_SITE_URL ??
  process.env.EXPO_PUBLIC_SITE_URL ??
  "";

/** هل يوجد عنوانٌ صالح؟ أقصرُ من `SITE_URL !== ""` في كل موضع. */
export const hasSite = (): boolean => SITE_URL.startsWith("http");

/**
 * جذرُ تطبيق الويب على النطاق (القاعدة ١٢٢).
 *
 * الموقعُ العامّ يملك `/` — الهبوطَ و`/u` و`/admin` و`/contact` — وتطبيقُ
 * الويب يجلس تحت `/app`. فما يقصد **شاشةً في التطبيق** يمرّ بـ`appUrl`،
 * وما يقصد الموقعَ العامّ يبقى على `SITE_URL` عارياً.
 *
 * ونسختُه في `src/lib/base.ts` للتطبيق نفسه: ذاك مشروعٌ بـnpm لا يرى
 * حزمَ pnpm، و`next.config.ts` يقرؤها منه قبل أن يُحلّ شيء. وهما سطرٌ
 * واحد، فإن تغيّر تغيّرا معاً.
 */
export const WEB_BASE = "/app";

/** رابطٌ مطلقٌ إلى شاشةٍ في التطبيق: `appUrl("/snap/callback")`. */
export const appUrl = (path: string): string =>
  hasSite() ? `${SITE_URL.replace(/\/+$/, "")}${WEB_BASE}${path}` : "";

/**
 * مهلةُ تأكيد البريد قبل أن يُحذف الحساب — بقرار المالك.
 *
 * حسابٌ يُسجَّل ببريدٍ ولا يُؤكَّد حسابٌ وهميّ، وتركُه يراكم في القاعدة
 * ما لا صاحب له. فيُكنَس — **وبشروطٍ أربعة لا يطال غيرَها**: له بريد
 * (فمن دخل بسناب لا بريد له أصلاً — القاعدة ١٢١ب)، وله كلمةُ مرور
 * (فمن دخل بمزوّدٍ لا كلمةَ له وحسابُه مؤكَّدٌ عند مزوّده)، وبلا هويّةٍ
 * مربوطة، وبلا لحظةٍ واحدة — فمن نشر شيئاً ليس وهميّاً.
 *
 * والمهلةُ قصيرة، والبريدُ يتأخّر أحياناً ويذهب إلى «غير الهامّ»: فهذا
 * الرقمُ هو ما يُرفع إن كثر من يشكو أنّ حسابه ذهب وهو يبحث عن الرسالة.
 */
export const UNVERIFIED_MINUTES = 10;

