-- «التمائم» صارت «التشارمز» بقرار المالك (القاعدة ٢٧١). التصنيفُ الذي يحمل اسمَ النوع
-- يُخفى بجانب شريحته بمطابقة الاسم (القاعدة ١٦٥)، فيُبدَّل اسمُه معه وإلّا ظهر شريحةً ثانية.
UPDATE "StoreCategory" SET "name" = 'التشارمز' WHERE btrim("name") = 'التمائم';
UPDATE "StoreCollection" SET "name" = replace("name", 'التمائم', 'التشارمز') WHERE "name" LIKE '%التمائم%';
