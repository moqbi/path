import { BASE } from "@/lib/base";

/**
 * نطاقُ الموقع من البيئة لا من الكود (القاعدة ١٠٥).
 *
 * والفراغُ ليس عطلاً: ما يحتاج رابطاً مطلقاً يقول إنّه لا يستطيع،
 * ولا يُكتب نطاقٌ في ملفٍّ يُنسى بعد أن يُحسم.
 */
export const SITE_URL: string = (
  process.env.SITE_URL ??
  process.env.NEXT_PUBLIC_SITE_URL ??
  ""
).replace(/\/+$/, "");

/**
 * رابطٌ مطلقٌ إلى **شاشةٍ في التطبيق**: `appUrl("/reset")`.
 *
 * `SITE_URL` وحده يصل إلى الموقع العامّ — الهبوط و`/u` و`/admin` — لا
 * إلى التطبيق، فهو تحت `/app` (القاعدة ١٢٢). وما يُكتب في رسالةِ بريدٍ
 * أو يُسجَّل عند مزوّدٍ خارجيّ لا يصحّحه أحدٌ بعد أن يخرج، فيُبنى من
 * هنا لا باليد.
 *
 * وما وجهتُه الموقعُ العامّ يبقى على `SITE_URL` عارياً: شعارُ الرسالة،
 * ورابطُ اللوحة في بريد الدعم.
 */
export const appUrl = (path: string): string => (SITE_URL ? `${SITE_URL}${BASE}${path}` : "");
